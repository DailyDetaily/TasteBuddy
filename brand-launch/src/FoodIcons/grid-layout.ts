export const foodIconsForGrid = (
  icons: readonly FoodIconEntry[],
  columns: number,
) => {
  const order = FOOD_ICON_GRID_ORDERS[columns] ?? FOOD_ICON_GRID_ORDERS[8];
  const positions = new Map(order.map((id, index) => [id, index]));
  // New catalog entries remain visible until the visual arrangement is updated.
  return [...icons].sort(
    (a, b) =>
      (positions.get(a.id) ?? order.length) -
      (positions.get(b.id) ?? order.length),
  );
};
