export type AxisID = "sweet" | "sour" | "salty" | "bitter" | "umami" | "fat";
export type Point = { x: number; y: number };
export type Bubble = Point & {
  id: string;
  kind: "native" | "extended";
  q: number;
  r: number;
  axis: AxisID;
  label: string;
  description: string;
  intensity: number;
  diameter: number;
  introDelay: number;
  primary: boolean;
};
export type BubbleRenderState = Bubble & {
  screenX: number;
  screenY: number;
  screenRadius: number;
  entrance: number;
  entranceOpacity: number;
  exitScale: number;
  exitOpacity: number;
  renderOpacity: number;
  fillOpacity: number;
  labelOpacity: number;
  enlarged: number;
  selected: number;
  highlight: number;
  outline: number;
  priority: number | null;
};
export type MapFrame = {
  bubbles: BubbleRenderState[];
  camera: Point;
  zoom: number;
  intro: number;
  veilOpacity: number;
  fullMapReveal: number;
  atlasReveal: number;
  loopSeconds: number;
  focusID: string | null;
  activeCellCount: number;
  addedCellCount: number;
  physicsCellCount: number;
  rotationDegrees: number;
  exitProgress: number;
  finalePhase: "interaction" | "shrink" | "grid-hold" | "reverse-exit" | "blank";
};
