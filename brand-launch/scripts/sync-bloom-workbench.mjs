// Bundle the actual app component without copying its geometry or sizing rules.
import { build } from "esbuild";
import { readFile, writeFile } from "node:fs/promises";
import { createHash } from "node:crypto";
import { fileURLToPath } from "node:url";
import path from "node:path";
const project = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const source = path.resolve(
  project,
  "../src/components/system/PalateBloomAvatar.tsx",
);
const digest = createHash("sha256")
  .update(await readFile(source))
  .digest("hex");
const result = await build({
  stdin: {
    contents: `export {default as SourceBloomAvatar, sortTasteProfile, TASTE_COLORS} from ${JSON.stringify(source)};`,
    resolveDir: project,
    loader: "tsx",
  },
  bundle: true,
  write: false,
  format: "esm",
  jsx: "automatic",
  platform: "browser",
  external: ["react", "react/jsx-runtime"],
  plugins: [
    {
      name: "standalone-svg",
      setup(builder) {
        builder.onLoad({ filter: /PalateBloomAvatar\.css$/ }, () => ({
          contents: "",
          loader: "js",
        }));
        builder.onResolve({ filter: /^\.\.\/ui\/utils$/ }, () => ({
          path: "svg-classes",
          namespace: "svg",
        }));
        // Only static, non-conflicting wrapper classes are used in this view.
        builder.onLoad({ filter: /.*/, namespace: "svg" }, () => ({
          contents:
            "export const cn = (...values) => values.filter(Boolean).join(' ')",
          loader: "js",
        }));
      },
    },
  ],
});
await writeFile(
  path.join(project, "src/TasteBloomWorkbench/source-avatar.generated.js"),
  `/* eslint-disable */\n// Generated by scripts/sync-bloom-workbench.mjs. Do not edit.\n// PalateBloomAvatar.tsx SHA256: ${digest}\n${result.outputFiles[0].text}`,
);
console.log("Synced live Bloom source component", digest.slice(0, 12));
