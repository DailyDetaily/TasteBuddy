import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const source = path.join(root, '../ios/TasteBuddy/Resources/Fixtures/dining-feedback-scenario.json');
const text = await readFile(source, 'utf8');
const axes = JSON.parse(text).tasteExperienceAxes;
const expected = ['sweet', 'sour', 'salty', 'bitter', 'umami', 'fat'];
if (!Array.isArray(axes) || axes.length !== 6 || expected.some(id => !axes.some(a => a.id === id))) {
  throw new Error('Native taste map requires its six known axes.');
}
const ids = new Set();
for (const axis of axes) for (const word of axis.words) {
  const id = `${axis.id}-${word.key}`;
  if (ids.has(id) || typeof word.label !== 'string' || !word.label || !Number.isFinite(axis.angle)) {
    throw new Error(`Invalid native bubble: ${id}`);
  }
  ids.add(id);
}
const output = path.join(root, 'src/TasteBubbleMapMotion/catalog.ts');
await mkdir(path.dirname(output), { recursive: true });
const hash = createHash('sha256').update(text).digest('hex');
await writeFile(output, '// Generated by scripts/sync-bubble-map-catalog.mjs. Axes/words only, no meal records.\n' +
  `export const BUBBLE_CATALOG_SOURCE_SHA256 = ${JSON.stringify(hash)};\n` +
  'export const BUBBLE_AXES = ' + JSON.stringify(axes, null, 2) + ' as const;\n');
console.log(`Exported ${ids.size} native taste expressions from six axes to ${output}`);
