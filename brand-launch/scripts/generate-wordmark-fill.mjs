// Build once after changing the source paths or terminal positions.
// Requires sharp, TypeScript, and Python with NumPy/Pillow. The app only loads
// the generated PNG fields and the metadata; no build tools run in Studio.
import fs from "node:fs/promises";
import path from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";
import { createHash } from "node:crypto";
import { spawnSync } from "node:child_process";
import ts from "typescript";
const require = createRequire(import.meta.url);
const sharp = require("sharp");
const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const loadTs = async (file) => {
  const compiled = ts.transpileModule(
    await fs.readFile(path.join(root, file), "utf8"),
    {
      compilerOptions: {
        module: ts.ModuleKind.ESNext,
        target: ts.ScriptTarget.ES2020,
      },
    },
  ).outputText;
  return import(
    `data:text/javascript;base64,${Buffer.from(compiled).toString("base64")}`
  );
};
const { logoGridElements } = await loadTs("src/LogoGrid/geometry.ts");
const { wordmarkTerminals } = await loadTs("src/LogoGrid/wordmarkTerminals.ts");
const output = path.join(root, "public/brand/logo-grid/wordmark-fill");
const audit = path.join(root, "output/logo-grid-round-fill-20260922");
await fs.mkdir(output, { recursive: true });
await fs.mkdir(path.join(audit, "glyph-masks"), { recursive: true });
const bounds = (d) => {
  const tokens = d.match(/[a-zA-Z]|-?\d*\.?\d+(?:e[-+]?\d+)?/g);
  const points = [];
  let i = 0,
    command,
    x = 0,
    y = 0;
  while (i < tokens.length) {
    if (/^[a-zA-Z]$/.test(tokens[i])) command = tokens[i++];
    if (command === "Z") {
      command = undefined;
      continue;
    }
    if (command === "H") {
      x = Number(tokens[i++]);
      points.push([x, y]);
    } else if (command === "V") {
      y = Number(tokens[i++]);
      points.push([x, y]);
    } else if (["M", "L", "C"].includes(command)) {
      for (let n = 0; n < (command === "C" ? 3 : 1); n++) {
        x = Number(tokens[i++]);
        y = Number(tokens[i++]);
        points.push([x, y]);
      }
      if (command === "M") command = "L";
    } else throw new Error(`Unsupported SVG command ${command}`);
  }
  const left = Math.floor(Math.min(...points.map((p) => p[0]))) - 2;
  const top = Math.floor(Math.min(...points.map((p) => p[1]))) - 2;
  return {
    x: left,
    y: top,
    width: Math.ceil(Math.max(...points.map((p) => p[0]))) + 2 - left,
    height: Math.ceil(Math.max(...points.map((p) => p[1]))) + 2 - top,
  };
};
const config = [];
for (const node of logoGridElements.filter((n) => n.role === "logo.wordmark")) {
  const box = bounds(node.props.d);
  const scale = 8;
  const filename = `${String(node.index).padStart(2, "0")}-${node.name.replace(".", "-")}.png`;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="${box.width * scale}" height="${box.height * scale}" viewBox="${box.x} ${box.y} ${box.width} ${box.height}"><rect x="${box.x}" y="${box.y}" width="${box.width}" height="${box.height}" fill="black"/><path d="${node.props.d}" fill="white"/></svg>`;
  const mask = path.join(audit, "glyph-masks", filename);
  await sharp(Buffer.from(svg)).greyscale().png().toFile(mask);
  config.push({
    index: node.index,
    name: node.name,
    ...box,
    scale,
    mask,
    terminals: wordmarkTerminals[node.index],
    sourceHash: createHash("sha256").update(node.props.d).digest("hex"),
    seedHash: createHash("sha256")
      .update(JSON.stringify(wordmarkTerminals[node.index]))
      .digest("hex"),
    destination: path.join(output, filename),
    src: `brand/logo-grid/wordmark-fill/${filename}`,
  });
}
const configPath = path.join(audit, "propagation-config.json");
await fs.writeFile(configPath, JSON.stringify(config, null, 2));
const run = spawnSync(
  process.env.WORDMARK_PYTHON ?? "python3",
  [path.join(root, "scripts/wordmark-distance-field.py"), configPath],
  { stdio: "inherit" },
);
if (run.status !== 0) process.exit(run.status ?? 1);
const result = JSON.parse(
  await fs.readFile(path.join(audit, "propagation-result.json"), "utf8"),
);
for (const item of result) {
  item.fieldHash = createHash("sha256")
    .update(await fs.readFile(item.destination))
    .digest("hex");
}
const maps = Object.fromEntries(
  result.map(
    ({
      index,
      src,
      x,
      y,
      width,
      height,
      maxDistance,
      terminalCount,
      sourceHash,
      seedHash,
      fieldHash,
    }) => [
      index,
      {
        src,
        x,
        y,
        width,
        height,
        maxDistance,
        terminalCount,
        sourceHash,
        seedHash,
        fieldHash,
      },
    ],
  ),
);
await fs.writeFile(
  path.join(root, "src/LogoGrid/wordmarkFillMaps.ts"),
  `// Generated by scripts/generate-wordmark-fill.mjs. Original SVG paths remain the final silhouette.\nexport type WordmarkFillMap = { src: string; x: number; y: number; width: number; height: number; maxDistance: number; terminalCount: number; sourceHash: string; seedHash: string; fieldHash: string };\nexport const wordmarkFillMaps: Record<number, WordmarkFillMap> = ${JSON.stringify(maps, null, 2)};\n`,
);
console.log(`Generated ${result.length} terminal-to-interior fields`);
