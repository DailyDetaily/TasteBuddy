import assert from 'node:assert/strict';
let handler;
globalThis.Deno = { env: { get: () => 'test-key' }, serve: value => { handler = value; } };
await import('./index.ts');
let calls = [];
const place = { id: 'ChIJtest-confirmed-place', displayName: { text: '테스트 주방' }, location: { latitude: 37.5, longitude: 127 }, formattedAddress: '테스트로 10', rating: 4.2 };
globalThis.fetch = async (url, options) => { calls.push({ url, options }); return Response.json(place); };
let response = await handler(new Request('https://local/', { method: 'POST', body: JSON.stringify({ placeId: place.id, query: '원래 상호' }) }));
assert.equal((await response.json()).place.placeId, place.id);
assert.ok(calls[0].url.includes('/places/ChIJtest-confirmed-place?'));
assert.equal(calls[0].options.headers['X-Goog-FieldMask'].startsWith('places.'), false);
calls = [];
globalThis.fetch = async (url, options) => { calls.push({ url, options }); return Response.json({ places: [{ ...place, id: 'wrong', displayName: { text: '다른 가게' } }, place] }); };
response = await handler(new Request('https://local/', { method: 'POST', body: JSON.stringify({ query: '테스트 주방', lat: 37.5, lng: 127 }) }));
assert.equal((await response.json()).place.placeId, place.id);
assert.equal(JSON.parse(calls[0].options.body).includedType, undefined);
globalThis.fetch = async () => new Response('', { status: 503 });
response = await handler(new Request('https://local/', { method: 'POST', body: JSON.stringify({ query: '테스트 주방' }) }));
assert.equal(response.status, 502);
response = await handler(new Request('https://local/', { method: 'POST', body: JSON.stringify({ placeId: '../invalid' }) }));
assert.equal(response.status, 400);
console.log('7 handler assertions passed');
